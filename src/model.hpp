
#pragma once

#include "matrix.hpp"

#include <span>
#include <vector>

using namespace std;

/**
 * @brief Общий интерфейс обучаемой модели.
 *
 * Признаки передаются как матрица с объектами в строках, а целевые значения —
 * как диапазон, где элемент с индексом строки задаёт ответ этого объекта.
 * Конкретная модель определяет допустимые значения и исключения.
 */
class IModel {
public:
    /** @brief Виртуальный деструктор для корректного удаления через IModel. */
    virtual ~IModel() = default;

    /**
     * @brief Обучает модель на матрице признаков и соответствующих откликах.
     * @param features Матрица размера n × d: n объектов и d признаков.
     * @param target Отклики длины n, сопоставленные строкам features по индексу.
     * @pre Для конкретной модели должны быть выполнены требования к данным,
     *      указанные её реализацией.
     * @post После успешного вызова модель подготовлена к предсказанию согласно
     *       контракту конкретной реализации.
     */
    virtual void fit(
        const Matrix& features,
        span<const double> target
    ) = 0;

    /**
     * @brief Вычисляет ответ модели для каждой строки матрицы признаков.
     * @param features Матрица размера m × d; число признаков d должно
     *        соответствовать обучающим данным конкретной модели.
     * @return Вектор из m ответов в порядке строк входной матрицы.
     * @pre Конкретная реализация может требовать предварительного вызова fit.
     */
    virtual vector<double> predict(
        const Matrix& features
    ) const = 0;
};

/**
 * @brief Интерфейс модели, предсказывающей числовой отклик.
 *
 * Использует общий контракт обучения и предсказания IModel.
 */
class IRegressor : public IModel {
public:
    /** @brief Виртуальный деструктор регрессора. */
    ~IRegressor() override = default;
};

/**
 * @brief Интерфейс модели классификации с вероятностным прогнозом.
 *
 * Порядок классов, возвращаемый classes(), задаёт порядок столбцов
 * predict_proba().
 */
class IClassifier : public IModel {
public:
    /** @brief Виртуальный деструктор классификатора. */
    ~IClassifier() override = default;

    /**
     * @brief Возвращает вероятности классов для объектов.
     * @param features Матрица размера m × d с объектами в строках.
     * @return Матрица размера m × K: строка соответствует объекту, столбец j
     *         — классу classes()[j].
     * @pre Модель должна быть обучена; требования к числу и значениям признаков
     *      задаются реализацией.
     */
    virtual Matrix predict_proba(
        const Matrix& features
    ) const = 0;

    /**
     * @brief Возвращает классы модели в порядке возрастания.
     * @return Невладеющий span меток классов. Для реализаций, хранящих классы
     *         внутри модели, срок действия span ограничен сроком жизни этих
     *         данных и может завершиться при повторном обучении.
     * @pre Модель должна быть обучена.
     */
    virtual span<const double> classes() const = 0;
};
